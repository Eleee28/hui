import { expectTypeOf, test } from "vitest";
import type * as Bots from "../api/bots.ts";
import type * as Triggers from "../api/bot-triggers.ts";

type LegacyBotFactKind = "fact" | "preference" | "decision";
type LegacyBotFactInput = { kind: LegacyBotFactKind; text: string; source?: string; pinned?: boolean };
type LegacyBotFact = {
  id: string;
  kind: LegacyBotFactKind;
  text: string;
  pinned: boolean;
  source: string;
  createdAt: string;
  updatedAt: string;
  revision: number;
};
type LegacyBotFactPatch = { kind?: LegacyBotFactKind; text?: string; pinned?: boolean; revision: number };

type LegacyBotTriggerSource = "listener";
type LegacyTriggerMatch = { field: string; op: "equals" | "contains"; value: string };
type LegacyBotTriggerFilter = { match?: LegacyTriggerMatch; prLinks?: true; bots?: true; external?: true };
type LegacyBotTriggerBase = {
  id: string;
  botId: string;
  name: string;
  source: LegacyBotTriggerSource;
  filter: LegacyBotTriggerFilter;
  prompt?: string;
  delivery?: "followUp" | "steer";
  enabled: boolean;
  cooldownSeconds: number;
  createdBy: "operator" | "bot";
  createdAt: string;
  updatedAt: string;
  lastFiredAt?: string;
  tokenHint?: string;
};
type LegacyBotTrigger = LegacyBotTriggerBase & { pending?: { events: number; until: string }; watch?: { polledAt?: string; error?: string } };
type LegacyBotTriggerRunStatus = "fired" | "coalesced" | "skipped" | "failed";
type LegacyBotTriggerRun = {
  id: string;
  triggerId: string;
  triggerName: string;
  at: string;
  status: LegacyBotTriggerRunStatus;
  events: number;
  summary: string;
  reason?: string;
  test?: true;
  catchUp?: true;
};
type LegacyBotTriggersList = { triggers: LegacyBotTrigger[]; runs: LegacyBotTriggerRun[]; deliveries: { lastHour: number; perHour: number } };
type LegacyBotTriggerCreated = { trigger: LegacyBotTrigger; hook: { token: string; path: string } };
type LegacyBotTriggerInput = { name: string; source: LegacyBotTriggerSource; filter: LegacyBotTriggerFilter; prompt?: string; delivery?: "followUp" | "steer"; enabled?: boolean; cooldownSeconds?: number };
type LegacyBotTriggerPatch = {
  name?: string;
  prompt?: string;
  delivery?: "followUp" | "steer";
  enabled?: boolean;
  cooldownSeconds?: number;
  filter?: Record<string, unknown>;
};

type LegacyBotTagging = "anyone" | "mention" | "nobody";
type LegacyBotFaceShape = "blob" | "round" | "triangle" | "heart" | "cookie" | "star" | "flower" | "cloud" | "drop" | "ghost" | "pill" | "block" | "hexagon";
type LegacyBotFaceEars = "cat" | "bear" | "bunny" | "antenna" | "sprout" | "horns";
type LegacyBotAvatar = { emoji?: string; color?: string; shape?: LegacyBotFaceShape; ears?: LegacyBotFaceEars };
type LegacyBotSkillRef = { name: string; path: string };
type LegacyBotSkillSelector = string | LegacyBotSkillRef;
type LegacyBotRecord = {
  id: string;
  handle: string;
  name: string;
  title?: string;
  description?: string;
  tagging?: Exclude<LegacyBotTagging, "anyone">;
  cwd: string;
  worker?: string;
  model?: string;
  thinking?: string;
  memoryModel?: string;
  memoryThinking?: string;
  avatar?: LegacyBotAvatar;
  voice?: Bots.BotVoice;
  hidden?: boolean;
  archived?: boolean;
  disabledTools?: string[];
  disabledSkills?: LegacyBotSkillRef[];
  sessionId: string;
  createdAt: string;
  updatedAt: string;
};
type LegacyBotInput = {
  name?: string;
  handle?: string;
  title?: string;
  description?: string;
  tagging?: LegacyBotTagging;
  soul?: string;
  cwd?: string;
  worker?: string;
  model?: string;
  thinking?: string;
  memoryModel?: string;
  memoryThinking?: string;
  avatar?: LegacyBotAvatar;
  voice?: Bots.BotVoice;
  hidden?: boolean;
  disabledTools?: string[];
  disabledSkills?: LegacyBotSkillSelector[];
};
type LegacyBotPatch = Partial<Omit<LegacyBotInput, "avatar" | "voice" | "soul" | "worker">> & { avatar?: LegacyBotAvatarPatch | null; voice?: LegacyBotVoicePatch | null };
type LegacyBotAvatarPatch = { emoji?: string; color?: string; shape?: LegacyBotFaceShape | ""; ears?: LegacyBotFaceEars | "" };
type LegacyBotVoicePatch = { language?: Bots.VoiceLanguage | ""; live?: Bots.GptLiveVoice | "" };
type LegacyBotSoul = { soul: string | null };
type LegacyBotSessionStatus = "idle" | "running" | "waiting" | "starting" | "error" | "reconnecting" | "disconnected";
type LegacyBotMemoryUsage = { calls: number; input: number; output: number; cacheRead: number; cacheWrite: number; cost: number };
type LegacyBotMemoryStatus = {
  messages: number;
  built: number;
  pending: number;
  viewBytes: number;
  viewLines: number;
  waiting?: boolean;
  failing?: { node: string; error: string; since: string };
  usage: LegacyBotMemoryUsage;
};
type LegacyBotLastMessage = { role: "user" | "assistant"; text: string; at: string };
type LegacyBotView = Omit<LegacyBotRecord, "worker"> & {
  worker?: { id: string; name: string };
  status: LegacyBotSessionStatus;
  soul: boolean;
  lastMessage?: LegacyBotLastMessage;
  unread: boolean;
  memory?: LegacyBotMemoryStatus;
  routines: number;
};
type LegacyBotQuestion = {
  id: string;
  method: "select" | "confirm" | "input" | "editor" | "secret" | "questionnaire";
  title: string;
  message?: string;
  options?: readonly string[];
  placeholder?: string;
  prefill?: string;
};
type LegacyBotDelivery = { status: "sent" | "queued" };
type LegacyBotReply = {
  status: "answered" | "failed" | "needs-input" | "timeout";
  reply?: string;
  error?: string;
  questions?: LegacyBotQuestion[];
};
type LegacyBotMessageResult = LegacyBotDelivery | LegacyBotReply;
type LegacyBotsUpdate = { revision: number; ids?: string[]; upserts: LegacyBotView[] };
type LegacyBotToolGroup = "files" | "shell" | "hui" | "extension" | "bots";
type LegacyBotCatalogTool = {
  name: string;
  label: string;
  description: string;
  group: LegacyBotToolGroup;
  source: string;
  powerful: boolean;
  enabled: boolean;
};
type LegacyBotCatalogSkill = LegacyBotSkillRef & {
  description: string;
  source: string;
  enabled: boolean;
};
type LegacyBotAccessRequest = {
  id: string;
  sessionId: string;
  title: string;
  message: string;
};
type LegacyBotCatalog = {
  tools: LegacyBotCatalogTool[];
  skills: LegacyBotCatalogSkill[];
  alwaysOn: { name: string; description: string }[];
  disabledTools: string[];
  disabledSkills: LegacyBotSkillRef[];
  live: boolean;
  request?: LegacyBotAccessRequest;
};

